"""The CBMC product-program generator: the self-composition harness of whole-function equivalence (ticket 61).

Created: 2026-10-14 ET (Probata proof of concept ticket 61). Format: docs/reference/format-v0.4-cbmc.md
("Whole-function equivalence").

Deterministic code, never an LLM. It is its own trusted tool (`swdb-cbmc-product-1`), beside ticket 22's CBMC
translator, so that adding it does not change the translator's sha256, which the method version
`method.probata-draft-1` pins (a method-version file is never edited in place). A method version must list this
generator in `c_lowering.translators` before a whole-function job runs under it. It reuses the translator's
expression and frame printers and its oracle prelude; the input draws and `main` follow `cbmc_translator.harness`
line for line, so one text compiles three ways (CBMC, differential run, replay) exactly as ticket 22's harness.
"""

import hashlib
from pathlib import Path

from swdb import cbmc_translator as tr

TOOL_ID = "swdb-cbmc-product"
TOOL_VERSION = "1"                  # bump on any change to what this generator prints
BASELINE_PREFIX = "swdb_base_"
EQUAL = "swdb_equal."


def identity():
    """{id, sha256} of the generator itself (this module's source)."""
    return {"id": f"{TOOL_ID}-{TOOL_VERSION}", "sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}


def renamed(text, names, prefix=BASELINE_PREFIX):
    """`text` with every name in `names` renamed to prefix + name by the preprocessor (the baseline's copy)."""
    defines = [f"#define {name} {prefix}{name}" for name in names]
    undefines = [f"#undef {name}" for name in names]
    return "\n".join(["/* the baseline's copy: its functions and globals renamed */", *defines, text.rstrip("\n"),
                      *undefines]) + "\n"


def product_harness(candidate, baseline, rows, *, sizes, cap, compared_globals, one_sided=()):
    """(C text, Plan, compared locations) of the self-composition harness of two versions of one function.

    `candidate` is the candidate artifact's function (names as lowered); `baseline` the baseline's, whose functions
    and globals carry BASELINE_PREFIX in the product program. One draw of inputs feeds both calls (each its own copy
    of every array); `rows` (a contract's formal halves, may be empty) are assumed (`requires`) and checked on the
    candidate's call as in `cbmc_translator.harness`. Then one property per output location: the return value, every
    element of every array parameter (all `cap` of them), and every global both versions' code names
    (`compared_globals`: (name, C type or None for an array)). A scalar global only one version's code names
    (`one_sided`: (name, C type, side)) is compared with its value before the call, which the other version (never
    naming it) leaves unchanged. Natively each compared location prints ` out <location> base=<x> cand=<y>`."""
    if [p[1] for p in candidate.parameters] != [p[1] for p in baseline.parameters] or \
            candidate.returns != baseline.returns:
        raise tr.Untranslatable(f"the candidate's {candidate.function} and the baseline's differ in their interface "
                                "(parameter or return types): whole-function equivalence compares the same boundary")
    for name in sizes:
        if not candidate.scalar(name):
            raise tr.Untranslatable(f"size bound {name} is not an integer parameter of {candidate.function}")
    plan = tr.Plan()
    counter = [0]
    caps = {p[0]: cap for p in candidate.parameters if p[2]}
    lines = [f"/* Generated by {TOOL_ID} {TOOL_VERSION}: the whole-function equivalence harness of "
             f"{candidate.function} (candidate) against {BASELINE_PREFIX}{baseline.function} (baseline). */",
             "static void swdb_run(void) {"]
    _inputs(candidate, rows, sizes, cap, plan, lines, caps, counter)
    arguments = []
    for name, ctype, pointer in candidate.parameters:
        if pointer:
            element = tr.element_type(ctype)
            lines.append(f"  {element} swdb_bbuf_{name}[{max(cap, 1)}];")
            lines.append(f"  for (int swdb_k = 0; swdb_k < {cap}; ++swdb_k) swdb_bbuf_{name}[swdb_k] = "
                         f"swdb_buf_{name}[swdb_k];")
            arguments.append(f"swdb_bbuf_{name}")
        else:
            arguments.append(name)
    for name, ctype, side in one_sided:
        if side == "baseline":
            lines.append(f"  {ctype} swdb_bold_{name} = {BASELINE_PREFIX}{name};")
    result = None
    call = f"{BASELINE_PREFIX}{baseline.function}({', '.join(arguments)})"
    own = f"{candidate.function}({', '.join(p[0] for p in candidate.parameters)})"
    if candidate.returns != "void":
        result = "swdb_result"
        lines.append(f"  {candidate.returns} swdb_bresult = {call};")
        lines.append(f"  {candidate.returns} swdb_result = {own};")
    else:
        lines.append(f"  {call};")
        lines.append(f"  {own};")
    for clause in rows:
        if clause.kind == "ensures":
            text = tr.expression(clause.text, candidate, "harness", result=result, caps=caps, counter=counter)
            lines.append(f'  SWDB_PROP({text}, "{clause.name}");')
        elif clause.kind == "assigns":
            lines.append(f'  SWDB_PROP({tr._frame(clause, candidate, cap, caps, counter)}, "{clause.name}");')
    pairs = []                                       # (location, baseline C, candidate C)
    if result:
        pairs.append(("result", "swdb_bresult", "swdb_result"))
    for name, _ctype, pointer in candidate.parameters:
        if pointer:
            pairs += [(f"{name}[{k}]", f"swdb_bbuf_{name}[{k}]", f"swdb_buf_{name}[{k}]") for k in range(cap)]
    arrays = []
    for name, ctype in compared_globals:
        if ctype:
            pairs.append((name, f"{BASELINE_PREFIX}{name}", name))
        else:
            arrays.append(name)
    for name, _ctype, side in one_sided:
        pairs.append((name, f"{BASELINE_PREFIX}{name}", f"swdb_bold_{name}") if side == "baseline" else
                     (name, f"swdb_old_{name}", name))
    for location, base, cand in pairs:
        lines.append(f'  SWDB_PROP({base} == {cand}, "{EQUAL}{location}");')
    for name in arrays:
        counter[0] += 1
        flag = f"swdb_e{counter[0]}"
        lines.append(f"  SWDB_PROP(({{ int {flag} = sizeof({name}) == sizeof({BASELINE_PREFIX}{name}); "
                     f"for (size_t swdb_k = 0; {flag} && swdb_k < sizeof({name}) / sizeof({name}[0]); ++swdb_k) "
                     f"if ({BASELINE_PREFIX}{name}[swdb_k] != {name}[swdb_k]) {flag} = 0; {flag}; }}), "
                     f'"{EQUAL}{name}");')
    lines.append(f'  SWDB_REACH("{tr.REACH_END}");')
    lines.append("#if defined(SWDB_NATIVE)")
    for location, base, cand in pairs:
        lines.append(f'  printf(" out {location} base=%lld cand=%lld", (long long) {base}, (long long) {cand});')
    for name in arrays:
        lines.append(f'  for (size_t swdb_k = 0; swdb_k < sizeof({name}) / sizeof({name}[0]); ++swdb_k) '
                     f'printf(" out {name}[%zu] base=%lld cand=%lld", swdb_k, '
                     f'(long long) {BASELINE_PREFIX}{name}[swdb_k], (long long) {name}[swdb_k]);')
    lines.append("#endif")
    lines.append("}")
    lines += _main(plan)
    return "\n".join(lines) + "\n", plan, [p[0] for p in pairs] + arrays


def _inputs(interface, rows, sizes, cap, plan, lines, caps, counter):
    """As cbmc_translator.harness: draw every input from the oracle, print it on replay, assume the size bounds and
    the `requires` clauses, and snapshot the pre-state (`swdb_old_*`)."""
    for name, ctype, pointer in interface.parameters:
        if pointer:
            continue
        lines.append(f"  {ctype} {name} = ({ctype}) swdb_next();")
        draw = {"name": name, "role": "size" if name in sizes else "value", "ctype": ctype}
        if name in sizes:
            draw["bound"] = sizes[name]
        plan.draws.append(draw)
    for name, ctype, pointer in interface.parameters:
        if not pointer:
            continue
        element = tr.element_type(ctype)
        lines.append(f"  {element} swdb_buf_{name}[{max(cap, 1)}];")
        lines.append(f"  for (int swdb_k = 0; swdb_k < {cap}; ++swdb_k) swdb_buf_{name}[swdb_k] = ({element}) swdb_next();")
        lines.append(f"  {ctype.replace('*', '').strip()} *{name} = swdb_buf_{name};")
        plan.draws += [{"name": f"{name}[{k}]", "role": "element", "ctype": element} for k in range(cap)]
    lines.append("#if defined(SWDB_REPLAY)")
    for draw in plan.draws:
        if draw["role"] == "element":
            pointer, index = draw["name"].split("[")
            lines.append(f'  printf(" input {draw["name"]}=%lld", (long long) swdb_buf_{pointer}[{index[:-1]}]);')
        else:
            lines.append(f'  printf(" input {draw["name"]}=%lld", (long long) {draw["name"]});')
    lines.append("#endif")
    for name, bound in sorted(sizes.items()):
        lines.append(f"  SWDB_ASSUME({name} <= {int(bound)}); /* size bound */")
    for clause in rows:
        if clause.kind == "requires":
            text = tr.expression(clause.text, interface, "harness", caps=caps, counter=counter)
            lines.append(f"  SWDB_ASSUME({text}); /* {clause.name} */")
    for name, ctype, pointer in interface.parameters:
        if pointer:
            element = tr.element_type(ctype)
            lines.append(f"  {element} swdb_old_{name}[{max(cap, 1)}];")
            lines.append(f"  for (int swdb_k = 0; swdb_k < {cap}; ++swdb_k) swdb_old_{name}[swdb_k] = swdb_buf_{name}[swdb_k];")
    for name, ctype in interface.globals:
        if ctype:
            lines.append(f"  {ctype} swdb_old_{name} = {name};")


def _main(plan):
    """As cbmc_translator.harness: under CBMC one run over an unconstrained oracle; natively one run per stdin line."""
    plan.capacity = plan.inputs + tr.HAVOC_BUDGET
    return [
        "#if defined(SWDB_CBMC)",
        "int main(void) {",
        f"  long long swdb_values[{plan.capacity}];",
        f"  swdb_oracle = swdb_values; swdb_oracle_n = {plan.capacity}; swdb_oracle_next = 0;",
        "  swdb_run();",
        "  return 0;",
        "}",
        "#else",
        "static char swdb_line[1 << 20];",
        f"static long long swdb_values[{plan.capacity}];",
        "int main(void) {",
        "  long long run = 0;",
        "  while (fgets(swdb_line, sizeof swdb_line, stdin)) {",
        "    char *at = swdb_line, *end;",
        "    long long count = 0;",
        f"    while (count < {plan.capacity}) {{ long long value = strtoll(at, &end, 10); if (end == at) break; "
        "swdb_values[count++] = value; at = end; }",
        "    swdb_oracle = swdb_values; swdb_oracle_n = count; swdb_oracle_next = 0;",
        "    printf(\"run %lld:\", run++);",
        "    int code = setjmp(swdb_jump);",
        "    if (code == 0) { swdb_run(); printf(\" end=done\\n\"); }",
        "    else printf(\" end=%s\\n\", code == 1 ? \"check\" : \"infeasible\");",
        "    fflush(stdout);",
        "  }",
        "  return 0;",
        "}",
        "#endif"]
